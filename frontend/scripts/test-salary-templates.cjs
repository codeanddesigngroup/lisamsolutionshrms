const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync('src/lib/salary-templates.ts', 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} };
vm.runInNewContext(output, context);
const { calculateSalary, baseFields } = context.exports;
const hr = { id: 'test-hr', departments: ['HR'], fields: baseFields.map(f => ({ ...f, enabled: !['commission', 'monthlySpiffs', 'weeklySpiffs'].includes(f.id) })) };
const sales = { id: 'test-sales', departments: ['Sales'], fields: baseFields.map(f => ({ ...f })) };
const values = { basicSalary: 50000, halfDayDeduction: 500, lateDeduction: 300, transportation: 2000, attendanceBonus: 1000, commission: 5000, monthlySpiffs: 1500, weeklySpiffs: 500 };
assert.equal(calculateSalary(values, hr).totalAmount, 52200, 'HR excludes commission and SPIFFs');
assert.equal(calculateSalary(values, sales).totalAmount, 59200, 'Sales includes both salary stages');
const hidden = JSON.parse(JSON.stringify(sales));
hidden.fields.find(f => f.id === 'commission').visible = false;
assert.equal(calculateSalary(values, hidden).totalAmount, 59200, 'Hidden earnings remain included');
hidden.fields.find(f => f.id === 'commission').enabled = false;
assert.equal(calculateSalary(values, hidden).totalAmount, 54200, 'Disabled earnings are excluded');
assert.equal(calculateSalary({ basicSalary: 100, penalties: 200 }, hr).netBasic, 0, 'Net basic retains zero floor');
const custom = JSON.parse(JSON.stringify(hr));
custom.fields.push({ id: 'custom', enabled: true, role: 'deduction', stage: 'totalAmount' });
assert.equal(calculateSalary({ basicSalary: 100, custom: 12.35 }, custom).totalAmount, 87.65, 'Custom final deductions work');
const snapshot = JSON.parse(JSON.stringify(custom));
custom.fields.at(-1).enabled = false;
assert.equal(calculateSalary({ basicSalary: 100, custom: 12.35 }, snapshot).totalAmount, 87.65, 'Saved snapshot keeps rules');
assert.equal(calculateSalary({ basicSalary: 0.1, transportation: 0.2 }, hr).totalAmount, 0.3, 'Currency is rounded');
const entries = [{ id: '1', label: 'Misconduct', amount: 500 }, { id: '2', label: 'Equipment damage', amount: 750.25 }];
assert.equal(context.exports.entryTotal(entries), 1250.25, 'Multiple amounts are summed');
assert.equal(calculateSalary({ basicSalary: 50000, penalties: context.exports.entryTotal(entries) }, hr).totalAmount, 48749.75, 'Penalty breakdown is deducted once');
assert.equal(context.exports.entryTotal([]), 0, 'Removing every entry clears the amount');
assert.equal(context.exports.entryTotal([{ amount: 0.1 }, { amount: 0.2 }]), 0.3, 'Breakdown rounds fractional amounts');
assert.equal(context.exports.fieldForDepartment([hr, sales], 'hr', 'penalties').id, 'penalties', 'Department matching ignores case');
console.log('13 salary calculation checks passed');
